#!/usr/bin/env node
// Turns a verified catalogue dataset (data/catalogs/*.json) into an idempotent
// SQL migration. The checksum (SHA-256 of the canonical requirements JSON) is
// stored with the catalogue version so any later edit is detectable.
//
//   node scripts/catalog/build-migration.mjs data/catalogs/<file>.json <YYYYMMDDHHMMSS>
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";

const [input, timestamp] = process.argv.slice(2);
if (!input || !/^\d{14}$/.test(timestamp ?? "")) {
  console.error("Usage: build-migration.mjs <dataset.json> <YYYYMMDDHHMMSS>");
  process.exit(1);
}

const fail = (msg) => {
  console.error(`✖ ${msg}`);
  process.exit(1);
};

const dataset = JSON.parse(readFileSync(input, "utf8"));
const { framework, version, requirements } = dataset;

if (
  !framework?.code ||
  !version?.version_label ||
  !Array.isArray(requirements) ||
  requirements.length === 0
) {
  fail("dataset is missing framework, version or requirements");
}
const codes = new Set();
for (const r of requirements) {
  for (const key of ["code", "category_code", "category_name", "title", "description", "source_reference"]) {
    if (typeof r[key] !== "string" || r[key].trim() === "") fail(`${r.code ?? "?"}: missing ${key}`);
  }
  if (codes.has(r.code)) fail(`duplicate code ${r.code}`);
  codes.add(r.code);
}

const sum = createHash("sha256").update(JSON.stringify(requirements)).digest("hex");

// Dollar-quoting avoids any escaping issue with the legal text.
const q = (value) => {
  if (value === null || value === undefined) return "null";
  const s = String(value);
  if (s.includes("$cat$")) fail("text contains the reserved delimiter $cat$");
  return `$cat$${s}$cat$`;
};

const rows = requirements
  .map(
    (r) =>
      `    (${q(r.code)}, ${q(r.category_code)}, ${q(r.category_name)}, ${q(r.title)}, ${q(r.description)}, ${q(r.source_reference)}, ${Number(r.sort_order) || 0})`,
  )
  .join(",\n");

const publishedAt = version.source_published_at ? `${q(version.source_published_at)}::date` : "null";

const sql = `-- =============================================================================
-- Regulatory catalogue: ${framework.code} ${version.version_label}
-- GENERATED by scripts/catalog/build-migration.mjs from ${basename(input)} — do not edit by hand.
-- Source: ${version.source_title}
-- Dataset SHA-256 (requirements): ${sum}
-- =============================================================================

insert into public.regulatory_frameworks (code, name, issuing_authority)
values (${q(framework.code)}, ${q(framework.name)}, ${q(framework.issuing_authority)})
on conflict (code) do nothing;

do $migration$
declare
  v_framework uuid := (select id from public.regulatory_frameworks where code = ${q(framework.code)});
  v_version   uuid;
begin
  if exists (select 1 from public.regulatory_framework_versions
             where framework_id = v_framework and version_label = ${q(version.version_label)}) then
    raise notice 'catalogue version already present, skipping';
    return;
  end if;

  insert into public.regulatory_framework_versions
    (framework_id, version_label, source_title, source_url, source_published_at, scope_note, dataset_checksum, status)
  values
    (v_framework, ${q(version.version_label)}, ${q(version.source_title)}, ${q(version.source_url)},
     ${publishedAt}, ${q(version.scope_note)}, '${sum}', 'draft')
  returning id into v_version;

  insert into public.requirements
    (framework_version_id, code, category_code, category_name, title, description, source_reference, sort_order)
  select v_version, r.code, r.category_code, r.category_name, r.title, r.description, r.source_reference, r.sort_order
  from (values
${rows}
  ) as r(code, category_code, category_name, title, description, source_reference, sort_order);

  -- Publishing makes the version immutable (see private.protect_published_catalogue).
  update public.regulatory_framework_versions set status = 'published' where id = v_version;
end;
$migration$;
`;

const slug = `${framework.code}_${version.version_label}`.replace(/[^a-z0-9]+/gi, "_").toLowerCase();
const out = resolve("supabase/migrations", `${timestamp}_catalog_${slug}.sql`);
writeFileSync(out, sql);
console.log(`✔ ${requirements.length} requirements → ${out}\n  checksum ${sum}`);
